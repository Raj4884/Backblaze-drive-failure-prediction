"""Command line: synth, build, train."""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from drive_failure.data import load_backblaze
from drive_failure.features import build_snapshots
from drive_failure.pipeline import format_report, run, save_bundle
from drive_failure.synth import make_daily

SNAPSHOTS = Path("data/snapshots.parquet")


def _save(df: pd.DataFrame, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        df.to_parquet(path)
        return path
    except ImportError:
        alt = path.with_suffix(".pkl")
        df.to_pickle(alt)
        return alt


def _load(path: Path) -> pd.DataFrame:
    for p in (path, path.with_suffix(".pkl")):
        if p.exists():
            return pd.read_parquet(p) if p.suffix == ".parquet" else pd.read_pickle(p)
    raise FileNotFoundError(f"{path} not found. Run `drive-failure build` or `synth` first.")


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="drive-failure")
    sub = p.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("build", help="build labelled snapshots from Backblaze daily CSV/ZIP files")
    b.add_argument("paths", nargs="+", type=Path, help="CSV or ZIP files, or directories")
    b.add_argument("--horizon", type=int, default=30)
    b.add_argument("--step", type=int, default=5, help="snapshot spacing in days; must divide 30")
    b.add_argument("--sample-frac", type=float, default=1.0, help="fraction of drives to keep")
    b.add_argument("--out", type=Path, default=SNAPSHOTS)

    s = sub.add_parser("synth", help="build snapshots from SYNTHETIC data (demo/testing only)")
    s.add_argument("--drives", type=int, default=600)
    s.add_argument("--days", type=int, default=400)
    s.add_argument("--seed", type=int, default=0)
    s.add_argument("--horizon", type=int, default=30)
    s.add_argument("--out", type=Path, default=SNAPSHOTS)

    t = sub.add_parser("train", help="train, calibrate, evaluate; write model and report")
    t.add_argument("--snapshots", type=Path, default=SNAPSHOTS)
    t.add_argument("--horizon", type=int, default=30)
    t.add_argument("--budget", type=float, default=0.01)
    t.add_argument("--seed", type=int, default=0)
    t.add_argument("--model-out", type=Path, default=Path("models/model.joblib"))
    t.add_argument("--report", type=Path, default=Path("REPORT.md"))
    t.add_argument("--synthetic", action="store_true", help="label the report as synthetic")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.cmd == "build":
        daily = load_backblaze(args.paths, args.step, args.sample_frac)
        snaps = build_snapshots(daily, args.horizon, args.step)
        out = _save(snaps, args.out)
        print(f"{len(snaps)} snapshots, {int(snaps['label'].sum())} positive -> {out}")
        return 0
    if args.cmd == "synth":
        snaps = build_snapshots(make_daily(args.drives, args.days, seed=args.seed), args.horizon)
        out = _save(snaps, args.out)
        print(f"SYNTHETIC: {len(snaps)} snapshots, {int(snaps['label'].sum())} positive -> {out}")
        return 0
    if args.cmd == "train":
        snaps = _load(args.snapshots)
        report, bundle = run(snaps, args.horizon, args.budget, args.seed)
        save_bundle(bundle, args.model_out)
        note = (
            "> SYNTHETIC DATA: generated by this repo. These numbers are not real results."
            if args.synthetic
            else ""
        )
        text = format_report(report, note)
        args.report.write_text(text, encoding="utf-8")
        print(text)
        return 0
    return 1
